def calc_checksum(pkt):
    v = 0x3692
    for b in pkt:
        v = (v >> 8) ^ CRC_TABLE[((b ^ v) & 0xFF)]
    return v


seq = [0x34EB]


def build_duml(src, dst, ct, cs, cid, payload=None):
    p = bytearray([0x55])
    length = 13 + (len(payload) if payload else 0)
    p += struct.pack('B', length & 0xff)
    p += struct.pack('B', (length >> 8) | 0x4)
    chk = 0x77
    for b in p[:3]:
        chk = HDR_CHECKSUM_TABLE[((b ^ chk) & 0xFF)]
    p += struct.pack('B', chk)
    p += struct.pack('BB', src, dst)
    p += struct.pack('<H', seq[0])
    p += struct.pack('BBB', ct, cs, cid)
    if payload:
        p += payload
    p += struct.pack('<H', calc_checksum(p))
    seq[0] = (seq[0] + 1) & 0xFFFF
    return p


def parse_axis(b):
    raw = int.from_bytes(b, 'little')
    v = (raw - 1024) * 50.97
    return int(max(-32767, min(32767, v)))


# ================================================================ 找串口
def find_port():
    ports = list(serial.tools.list_ports.comports())
    if not ports:
        print("[错误] 没有任何串口。检查遥控器是否开机、数据线是否插好。")
        sys.exit(1)

    print("可用串口：")
    for p in ports:
        print(f"   {p.device:<8} {p.description}")

    for p in ports:
        if "For Protocol" in (p.description or ""):
            return p.device

    print("[错误] 未找到 For Protocol 串口（COM3 是调试口，不可用）")
    sys.exit(1)


